"""Generate imgui_brutal.cpp: Brutal.ImGui's flat C API (1146 functions; names and managed signatures
decoded from the game's Brutal.ImGui.dll into brutal_imgui_signatures.txt) over Dear ImGui
1.92.2-docking, for RimWorld 1.7 on Android.

usage: gen_imgui.py signatures.txt imgui.h imgui_internal.h out.cpp [overrides.tsv]

Naming (checked against the game's libimgui.so): Foo / Foo_N -> ImGui::Foo (the overload picked by
the argument types), Foo_internal / Foo_internal_N -> internal ImGui::Foo or global ::Foo
(imgui_internal.h), Type_Method -> self->Method (ImDrawList's internals have a leading underscore in
C++). Arguments are adapted, not converted: vectors the managed side passes by pointer go through
Ref<T> (T&, T* or float*), pointers to plain values through Ptr<T> (T* or T&), integer callbacks
through Any (any pointer type). Return types are deduced (decltype(auto)); a C++ reference comes back
as a pointer, which is what the managed side declares. overrides.tsv holds the few bodies the rules
cannot express.
"""
import re, sys

sigs = open(sys.argv[1], encoding='utf-8').read().split('\n')
headers = open(sys.argv[2], encoding='utf-8').read() + open(sys.argv[3], encoding='utf-8').read()
out = sys.argv[4]
overrides = {}
if len(sys.argv) > 5:
    for line in open(sys.argv[5], encoding='utf-8'):
        line = line.rstrip('\n')
        if line and not line.startswith('#'):
            name, body = line.split('\t', 1)
            overrides[name] = body

structs = set(re.findall(r'\bstruct\s+(?:IMGUI_API\s+)?(Im\w+)', headers))

VEC = {'float2': 'ImVec2', 'float4': 'ImVec4', 'floatRect': 'ImRect', 'ImTextureRef': 'ImTextureRef',
       'ImGuiListClipperRange': 'ImGuiListClipperRange'}
SIMPLE = {'byte*': 'const char*', 'Bool8': 'bool', 'Bool8*': 'bool*', 'float': 'float', 'int': 'int',
          'uint': 'unsigned int', 'double': 'double', 'long': 'long long', 'ulong': 'unsigned long long',
          'ushort': 'unsigned short', 'nint': 'intptr_t', 'nuint': 'size_t', 'void*': 'void*',
          'void**': 'void**', 'float*': 'float*', 'int*': 'int*', 'uint*': 'unsigned int*',
          'double*': 'double*', 'long*': 'long long*', 'ulong*': 'unsigned long long*', 'nint*': 'intptr_t*',
          'nuint*': 'size_t*', 'float3*': 'float*', 'int2*': 'int*', 'int3*': 'int*', 'int4*': 'int*',
          'byte**': 'const char**', 'float2': 'ImVec2', 'float4': 'ImVec4', 'floatRect': 'ImRect',
          'ImVector`1<uint>*': 'ImVector<ImGuiID>*', 'ImVector`1<ImDrawListPtr>*': 'ImVector<ImDrawList*>*',
          'ImVector`1<ImGuiWindowPtr>*': 'ImVector<ImGuiWindow*>*',
          'ImVector`1<Ptr`1<byte>>*': 'ImVector<const char*>*', 'void': 'void'}
# Pointers to plain values: the callee may want T* or T& (ColorConvertHSVtoRGB's float& outputs).
PRIM_PTR = {'float*', 'int*', 'uint*', 'Bool8*', 'double*', 'long*', 'ulong*', 'float3*', 'int2*', 'int3*', 'int4*'}
# ImDrawList's internal helpers are spelled with a leading underscore in C++.
UNDERSCORED = {'ImDrawList': {'CalcCircleAutoSegmentCount', 'ClearFreeMemory', 'OnChangedClipRect',
    'OnChangedTexture', 'OnChangedVtxOffset', 'PathArcToFastEx', 'PathArcToN', 'PopUnusedDrawCmd',
    'ResetForNewFrame', 'SetDrawListSharedData', 'SetTexture', 'TryMergeDrawCmds'}}

def ctype(t):
    if t in SIMPLE: return SIMPLE[t]
    if t.endswith('*') and t[:-1] in VEC: return 'const %s*' % VEC[t[:-1]]
    return t   # ImGui types, enums and flags keep their names

def split_name(name, args):
    base = re.sub(r'_\d+$', '', name)            # Foo_internal_1 -> Foo_internal
    if base.endswith('_internal'): base = base[:-len('_internal')]
    base = re.sub(r'_\d+$', '', base)            # Foo_1_internal -> Foo
    if args and args[0].endswith('*'):
        t = args[0][:-1]
        t = VEC.get(t, t)
        if t in structs and base.startswith(t + '_'):
            method = base[len(t) + 1:]
            if method in UNDERSCORED.get(t, ()): method = '_' + method
            return 'member', t, method
    return 'free', None, base

lines = ['// GENERATED by tools/rimworld17/gen_imgui.py — do not edit; see imgui_brutal.h.',
         '#include "imgui_brutal.h"', '']
for i, line in enumerate(sigs):
    line = line.strip()
    if not line: continue
    m = re.match(r'(.+?) (\w+)\((.*)\)$', line)
    ret, name, argstr = m.groups()
    args = [a.strip() for a in argstr.split(',') if a.strip()]
    kind, cls, method = split_name(name, args)
    params, call = [], []
    for j, a in enumerate(args):
        params.append('%s a%d' % (ctype(a), j))
        if a.endswith('*') and a[:-1] in VEC: call.append('Ref<%s>{a%d}' % (VEC[a[:-1]], j))
        elif a in PRIM_PTR: call.append('Ptr<%s>{a%d}' % (ctype(a)[:-1], j))
        elif a == 'nint': call.append('Any{a%d}' % j)
        else: call.append('a%d' % j)
    if name in overrides:
        body = overrides[name]
    elif kind == 'member':
        self_arg = call[0] if args[0][:-1] in VEC else 'a0'
        body = 'return static_cast<%s*>(%s)->%s(%s);' % (cls, self_arg, method, ', '.join(call[1:])) \
            if args[0][:-1] in VEC else 'return a0->%s(%s);' % (method, ', '.join(call[1:]))
    else:
        body = 'using namespace ImGui; return %s(%s);' % (method, ', '.join(call))
    w = 'rdw_%d' % i
    lines.append('extern "C" RDW decltype(auto) %s(%s) __asm__("%s");' % (w, ', '.join(params), name))
    lines.append('extern "C" RDW decltype(auto) %s(%s) { %s }' % (w, ', '.join(params), body))
open(out, 'w', encoding='utf-8', newline='\n').write('\n'.join(lines) + '\n')
print(len([s for s in sigs if s.strip()]), 'signatures ->', out)
